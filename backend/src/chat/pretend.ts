/**
 * 「やったフリ」の検知。
 *
 * モデルは、履歴に並ぶ成功メッセージを真似て「移動しました」とだけ書き、
 * ツールを呼ばないことがある。そのまま出すと、利用者は終わったと思って
 * 画面を閉じてしまう。食い違いを見つけて、正しい次の一手を案内する。
 *
 * ただし注意書きの出しすぎは、それ自体が混乱の元になる。
 * 実際に次の2つが報告された。
 *
 * 1. システムが書いた成功メッセージ(「🗑 フォルダ『X』をゴミ箱に移動しました」)
 *    にまで反応し、成功した操作に「実際には移動していません」と付けていた
 * 2. モデルが「どれを移動しますか?」と聞き返しているのに
 *    「実際には移動していません」と付けていた(読めば分かることを繰り返していた)
 *
 * そこで、見るのは**モデル自身が書いた文だけ**にし、
 * 「やりました」(完了の主張)と「やります」(これからの宣言)を分けて扱う。
 */

interface Check {
  /** この言い回しに対応するツール名 */
  tool: string;
  /** 完了を主張する言い回し。嘘になるので必ず注意する */
  done: RegExp;
  /** これからやると宣言する言い回し。状況次第では注意しない */
  intent: RegExp;
  note: string;
}

/**
 * 言い回しは列挙で書く。`.{0,8}(ます|ました)` のような緩い書き方だと
 * 「移動できます」「移動する方法を説明します」まで拾ってしまう
 */
const CHECKS: Check[] = [
  {
    tool: 'reclassify_all_manuals',
    done: /再分類(が|を)?(完了しました|終わりました|しました)/,
    intent: /再分類(を実行)?します/,
    note: '(再分類はまだ実行されていません。「全マニュアルを再分類して」と送ると、確認のうえ実行します)',
  },
  {
    tool: 'add_classification_rule',
    done: /(分類ルール|ルール)[^。]{0,12}(追加|登録|保存|設定)(し|いたし)ました/,
    intent:
      /(分類ルール|ルール)[^。]{0,12}(追加|登録|保存|設定)(し|いたし)ます/,
    note: '⚠️ 実際にはルールは登録されていません。サイドバーの「分類ルール」から登録すると確実です。',
  },
  {
    tool: 'move_manual',
    done: /(移動しました|移動させました|移動しておきました|移しました|移動が完了)/,
    intent: /(移動します|移動しますね|移動させます|移動しておきます|移します)/,
    note: '⚠️ 実際には移動していません。「〇〇のマニュアルを△△フォルダに移動して」と送るか、一覧画面でドラッグして移動してください。',
  },
  {
    tool: 'update_folder',
    done: /(フォルダ名|フォルダの名前)[^。]{0,14}(変更しました|変えました|改名しました)/,
    intent:
      /(フォルダ名|フォルダの名前)[^。]{0,14}(変更します|変えます|改名します)/,
    note: '⚠️ 実際には名前は変わっていません。もう一度「〇〇フォルダの名前を△△に変えて」と送ってください。',
  },
  {
    tool: 'delete_folder',
    done: /フォルダ[^。]{0,14}(削除しました|消しました|ゴミ箱に移動しました)/,
    intent: /フォルダ[^。]{0,14}(削除します|消します)/,
    note: '⚠️ 実際には削除していません。もう一度「〇〇フォルダを削除して」と送ってください。',
  },
  {
    tool: 'create_folder',
    done: /フォルダ[^。]{0,14}(作成しました|作りました)/,
    intent: /フォルダ[^。]{0,14}(作成します|作ります)/,
    note: '⚠️ 実際にはフォルダは作成されていません。もう一度「〇〇というフォルダを作って」と送ってください。',
  },
];

export interface PretendContext {
  /** モデル自身が書いた文(システムが足した成功メッセージを含めない) */
  modelText: string;
  /** この応答で実際に呼ばれたツール名 */
  calledTools: string[];
  /** 選択肢を出しているか(出しているなら聞き返している最中) */
  hasOptions: boolean;
}

/** 応答に添える注意書きを組み立てる。何も無ければ空 */
export function pretendNotes({
  modelText,
  calledTools,
  hasOptions,
}: PretendContext): string[] {
  const text = modelText.trim();
  if (!text) return [];

  // 何か1つでも実行できたなら、「これからやります」への注意は要らない。
  // 利用者から見れば動いているので、そこに「していません」を足すと矛盾に見える
  const didSomething = calledTools.length > 0;
  // 聞き返している応答は、やっていないことが読めば分かる
  const isAsking = hasOptions || /[？?]\s*$/.test(text);

  const notes: string[] = [];
  for (const check of CHECKS) {
    if (calledTools.includes(check.tool)) continue;
    // 完了を主張しているなら、それは事実と違うので必ず伝える
    if (check.done.test(text)) {
      notes.push(check.note);
      continue;
    }
    // これからやると言っただけの場合は、状況が紛らわしいときだけ伝える
    if (!didSomething && !isAsking && check.intent.test(text)) {
      notes.push(check.note);
    }
  }
  return notes;
}
