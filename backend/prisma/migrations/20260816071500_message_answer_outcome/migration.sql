-- 回答の「結末」を記録する列。
--
-- answered_from_manuals だけでは、判定できない場合がすべて null に潰れる。
-- 実際の本番データを数えたところ、記録開始後の未判定12件の内訳は
-- 聞き返し4件・管理操作4件・生成失敗3件・申告漏れ1件だった。
-- これらが同じ null では「仕組みが動いていないのか、集計対象外が多いだけか」
-- を画面から区別できず、利用状況が読み取れない。
--
-- 入る値(RAG側のOUTCOME_*と対応):
--   answered   … 抜粋を根拠に答えた
--   no_basis   … 根拠が無いと申告した(=答えられなかった)
--   clarify    … 聞き返した(絞り込み質問)。まだ続きがある
--   admin      … 管理操作(フォルダ作成など)の応答
--   failed     … 回答文の生成に失敗した
--   unreported … 通常の回答だが[参照]の申告が無く、可否を判定できない
--   no_manuals … そもそも検索できるマニュアルが無い
--   null       … この列より前に保存されたデータ(記録開始前)
--
-- 注意: prisma migrate devが生成するSQLには、生SQLで作った検索用
-- インデックス(pg_trgm / HNSW)のDROPが必ず混ざる。消すと本番の検索が
-- 黙って壊れるため、このALTER TABLEだけを残して手で書いている。
ALTER TABLE "Message" ADD COLUMN "answer_outcome" TEXT;
